#!/usr/bin/env python3
"""Offline, manually invoked private MP4 render of receipt-verified staged photos.

No Supabase/YouTube access, no job updates, no file overwrite. Two files:
 - RealtyFlow private-stage-receipt.json generated by the trusted photo intake.
 - Reviewable, operator-created scene plan JSON (format below).
Final song and cabinet checksums must be supplied explicitly.
"""
import argparse
import hashlib
import json
import math
import re
import tempfile
from pathlib import Path
from importlib.util import module_from_spec, spec_from_file_location

FILE_RE = re.compile(r"^photo-(0[0-9]|1[01])\.(jpg|png|webp)$")
SHA_RE = re.compile(r"^[a-f0-9]{64}$")
UUID_RE = re.compile(r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$")
SECTIONS = {"opening", "verse1", "verse2", "verse3", "chorus", "bridge", "solo", "outro"}
MAX_TOTAL_BYTES = 120 * 1024 * 1024


def module(name: str):
    spec = spec_from_file_location(name.replace("-", "_"), Path(__file__).with_name(name))
    result = module_from_spec(spec)
    spec.loader.exec_module(result)
    return result


def file_sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def read_json(path: Path, max_bytes: int = 60_000) -> dict:
    if not path.is_file() or path.stat().st_size > max_bytes:
        raise ValueError("Missing or oversized scene document")
    try:
        result = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError, UnicodeError) as exc:
        raise ValueError("Invalid scene document") from exc
    if not isinstance(result, dict):
        raise ValueError("Scene document must be an object")
    return result


def validate_staged_scene_plan(stage_dir: Path, scene_plan: Path, expected_job: str,
                               expected_song: str, expected_master: str) -> tuple[list[Path], list[dict], dict]:
    if not UUID_RE.fullmatch(expected_job) or not UUID_RE.fullmatch(expected_song):
        raise ValueError("Invalid job or song identifier")
    if not SHA_RE.fullmatch(expected_master):
        raise ValueError("Invalid expected song master hash")
    receipt = read_json(stage_dir / "private-stage-receipt.json")
    plan = read_json(scene_plan)
    if (receipt.get("version") != 1 or receipt.get("jobId") != expected_job
            or receipt.get("songId") != expected_song
            or receipt.get("masterSha256") != expected_master
            or receipt.get("workerStatus") != "images_decoded_staged_only"
            or receipt.get("publish") is not False):
        raise ValueError("Untrusted private image staging receipt")
    if (plan.get("version") != 1 or plan.get("jobId") != expected_job
            or plan.get("songId") != expected_song
            or plan.get("publish") is not False
            or plan.get("format") not in ("landscape", "portrait")
            or plan.get("seconds") not in ("full", 15, 30, 60)
            or type(plan.get("endWithLastScene")) is not bool):
        raise ValueError("Invalid private render scene plan")
    receipts = receipt.get("images")
    scenes = plan.get("scenes")
    if not isinstance(receipts, list) or not isinstance(scenes, list):
        raise ValueError("Missing staged scene metadata")
    if not (1 <= len(receipts) == len(scenes) <= 12):
        raise ValueError("Stage and scene plan must have the same number of images")
    if receipt.get("imageCount") != len(receipts):
        raise ValueError("Stage receipt image count mismatch")
    files: list[Path] = []
    total = 0
    for index, (item, scene) in enumerate(zip(receipts, scenes)):
        if not isinstance(item, dict) or not isinstance(scene, dict):
            raise ValueError("Invalid scene item")
        filename = item.get("filename")
        match = FILE_RE.fullmatch(filename) if isinstance(filename, str) else None
        if (not match or int(match.group(1)) != index
                or item.get("index") != index or scene.get("filename") != filename
                or item.get("mime") not in ("image/jpeg", "image/png", "image/webp")
                or not isinstance(item.get("sha256"), str)
                or not SHA_RE.fullmatch(item["sha256"])
                or item["mime"] != {"jpg":"image/jpeg","png":"image/png","webp":"image/webp"}[match.group(2)]):
            raise ValueError("Mismatched or unsafe photo file in stage receipt")
        if (scene.get("section") not in SECTIONS
                or type(scene.get("weight")) is not int
                or scene["weight"] not in (1, 2, 3)):
            raise ValueError("Invalid video section or weight")
        if "cueStart" in scene and (type(scene["cueStart"]) not in (int, float)
                or not math.isfinite(scene["cueStart"]) or scene["cueStart"] < 0):
            raise ValueError("Invalid manual scene timestamp")
        file = stage_dir / filename
        if file.is_symlink() or not file.is_file():
            raise ValueError("Staged photo missing or is a symbolic link")
        size = file.stat().st_size
        if (type(item.get("bytes")) is not int or size != item["bytes"]
                or size < 1024 or size > 10 * 1024 * 1024):
            raise ValueError("Staged photo byte count mismatch")
        total += size
        if total > MAX_TOTAL_BYTES or file_sha256(file) != item["sha256"]:
            raise ValueError("Staged photo checksum mismatch")
        files.append(file)
    return files, scenes, plan


def timed_assignments(scenes: list[dict], seconds: float, portrait: bool,
                      end_with_last: bool) -> list[dict]:
    if not math.isfinite(seconds) or not 2 < seconds <= 3600:
        raise ValueError("Invalid master duration")
    intro = min(3, seconds * .12) if portrait else min(30, seconds * .20)
    outro = 0 if end_with_last else (min(3, seconds * .12) if portrait else min(15, seconds * .10))
    middle = seconds - intro - outro
    cues = ["cueStart" in scene for scene in scenes]
    if any(cues) and not all(cues):
        raise ValueError("Incomplete manual scene timestamps")
    if all(cues):
        starts = [float(scene["cueStart"]) for scene in scenes]
        if (starts[0] < intro or any(start >= seconds - outro for start in starts)
                or any(starts[i] <= starts[i-1] for i in range(1, len(starts)))):
            raise ValueError("Manual scenes are overlapping or outside song window")
        result = [
            {"section": scene["section"], "clip": f"photo-scene-{index:02d}.mp4",
             "start": round(start, 4),
             "end": round(starts[index+1] if index+1 < len(starts) else seconds-outro, 4)}
            for index, (scene, start) in enumerate(zip(scenes, starts))
        ]
        module("compose-jukebox-sections.py").build_section_plan(seconds, result)
        return result
    total = sum(scene["weight"] for scene in scenes)
    cursor = intro
    result = []
    for index, scene in enumerate(scenes):
        end = seconds - outro if index == len(scenes)-1 else cursor + middle * scene["weight"] / total
        result.append({"section": scene["section"], "clip": f"photo-scene-{index:02d}.mp4",
                       "start": round(cursor, 4), "end": round(end, 4)})
        cursor = end
    module("compose-jukebox-sections.py").build_section_plan(seconds, result)
    return result


def render_stage(stage_dir: Path, scene_plan: Path, audio: Path, cabinet: Path, output: Path,
                 job_id: str, song_id: str, master_sha: str, cabinet_sha: str,
                 plan_only: bool = False):
    files, scenes, plan = validate_staged_scene_plan(
        stage_dir, scene_plan, job_id, song_id, master_sha)
    portable = module("render-jukebox-portable-project.py")
    portable.verify_sha256(audio, master_sha)
    portable.verify_sha256(cabinet, cabinet_sha)
    composer = module("compose-jukebox-video.py")
    duration = composer.probe_media(audio, "audio")
    composer.probe_media(cabinet, "video")
    if plan["seconds"] != "full":
        duration = min(duration, plan["seconds"])
    portrait = plan["format"] == "portrait"
    assignments = timed_assignments(scenes, duration, portrait, plan["endWithLastScene"])
    if output.exists() or output.resolve() in (
        audio.resolve(), cabinet.resolve(), scene_plan.resolve()):
        raise ValueError("Output exists or overlaps render input")
    receipt = {"version": 1, "jobId": job_id, "songId": song_id,
               "masterSha256": master_sha, "cabinetSha256": cabinet_sha,
               "format": plan["format"], "durationSeconds": duration,
               "assignments": assignments, "publish": False}
    if plan_only:
        return receipt
    renderer = module("render-jukebox-photos.py")
    sections = module("compose-jukebox-sections.py")
    with tempfile.TemporaryDirectory(prefix="jukebox-render-") as temp:
        clips = []
        for index, file in enumerate(files):
            dest = Path(temp) / f"photo-scene-{index:02d}.mp4"
            renderer.render_photo(file, dest,
                                  assignments[index]["end"]-assignments[index]["start"],
                                  portrait)
            clips.append(dest)
        sections.compose_sections(audio, cabinet, clips, assignments, output,
                                  portrait, seconds=duration)
        receipt["videoSha256"] = file_sha256(output)
        receipt["videoBytes"] = output.stat().st_size
    return receipt


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--stage-dir", type=Path, required=True)
    parser.add_argument("--scene-plan", type=Path, required=True)
    parser.add_argument("--audio", type=Path, required=True)
    parser.add_argument("--cabinet", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--job-id", required=True)
    parser.add_argument("--song-id", required=True)
    parser.add_argument("--master-sha256", required=True)
    parser.add_argument("--cabinet-sha256", required=True)
    parser.add_argument("--plan-only", action="store_true")
    args = parser.parse_args()
    result = render_stage(
        args.stage_dir, args.scene_plan, args.audio, args.cabinet, args.output,
        args.job_id, args.song_id, args.master_sha256, args.cabinet_sha256,
        plan_only=args.plan_only)
    print(json.dumps(result, ensure_ascii=False, indent=2))
